#!/usr/bin/env bun
// Generates src/lib/components/view-registry.ts from the coordinator-owned inventory (docs/plan/view-coverage.json)
// and the Linear map (docs/plan/work-items.json). `--check` fails when the committed registry differs, so `check`
// catches a registry edited by hand or an inventory changed without regenerating.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'src', 'lib', 'components', 'view-registry.ts');
const inventory = JSON.parse(readFileSync(join(root, 'docs', 'plan', 'view-coverage.json'), 'utf8')) as { reference: string; documentCount: number; views: { id: string; label: string; group: string; owner: string }[] };
const plan = JSON.parse(readFileSync(join(root, 'docs', 'plan', 'work-items.json'), 'utf8')) as { items: { key: string; linear?: { identifier?: string } }[] };
const items = new Map(plan.items.map((i) => [i.key, i]));

/** Route category per owning M2 ticket (coordinator decision 2). The pilot's own views have fixed routes. */
const CATEGORY: Record<string, string> = { 'CC-04': 'evidence', 'CC-05': 'analysis', 'CC-06': 'quantum', 'CC-07': 'registers', 'CC-08': 'litigation', 'CC-09': 'bundles', 'CC-10': 'system' };
const PILOT = 'CC-03';
/** Views the pilot implements; every other entry stays unavailable until its owner's ticket passes. */
const AVAILABLE = new Set(['overview', 'chronology']);

const linear = (key: string) => {
	const id = items.get(key)?.linear?.identifier;
	if (!id) throw new Error(`no Linear identifier for ${key} in docs/plan/work-items.json`);
	return id;
};
if (inventory.views.length !== 42) throw new Error(`the inventory lists ${inventory.views.length} views, not 42`);
const ids = new Set<string>();
const entries = inventory.views.map((v) => {
	if (!/^[a-z][a-z0-9_]{0,63}$/.test(v.id) || ids.has(v.id)) throw new Error(`invalid or duplicate view id ${v.id}`);
	ids.add(v.id);
	const pilot = v.owner === PILOT;
	const category = pilot ? null : CATEGORY[v.owner];
	if (!pilot && !category) throw new Error(`view ${v.id}: owner ${v.owner} has no route category`);
	const issue = linear(v.owner);
	return {
		id: v.id, label: v.label, group: v.group, owner: v.owner, linear: issue, category,
		route: pilot ? `/${v.id}` : `/${category}/${v.id}`,
		status: AVAILABLE.has(v.id) ? 'available' : `unavailable-until:${issue}`,
	};
});

const q = (v: unknown) => (v === null ? 'null' : `'${String(v).replace(/[\\']/g, (c) => `\\${c}`)}'`);
const literal = (o: Record<string, unknown>) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${q(v)}`).join(', ')} }`;

const body = `// GENERATED by scripts/pilot/generate-view-registry.ts from docs/plan/view-coverage.json and docs/plan/work-items.json.
// Do not edit by hand: change the inventory (coordinator-owned) and regenerate. \`bun run --bun check\` fails on drift.
// Reference inventory: ${inventory.documentCount} documents, ${entries.length} views.
// route is relative to /v/<encoded resultsVersion>. status flips to 'available' when the owning ticket passes its gate.

export type ViewCategory = ${Object.values(CATEGORY).map((c) => `'${c}'`).join(' | ')};
export type ViewStatus = 'available' | \`unavailable-until:\${string}\`;
export interface ViewEntry {
	/** v5 navigation id */
	id: string;
	/** task name shown in navigation; matches the destination heading (BA-18) */
	label: string;
	/** navigation group in the v5 order */
	group: string;
	/** owning planning key */
	owner: string;
	/** owning Linear issue */
	linear: string;
	/** route subtree owned by the M2 ticket; null for the pilot's own views */
	category: ViewCategory | null;
	route: string;
	status: ViewStatus;
}

export const VIEWS: readonly ViewEntry[] = Object.freeze([
${entries.map((e) => `\t${literal(e)},`).join('\n')}
].map((e) => Object.freeze(e as ViewEntry)));

export const VIEW_GROUPS: readonly string[] = Object.freeze([${[...new Set(entries.map((e) => e.group))].map(q).join(', ')}]);
export const CATEGORIES: Readonly<Record<ViewCategory, { owner: string; linear: string }>> = Object.freeze({
${Object.entries(CATEGORY).map(([k, c]) => `\t${c}: { owner: ${q(k)}, linear: ${q(linear(k))} },`).join('\n')}
});
`;

if (process.argv.includes('--check')) {
	let current = '';
	try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
	if (current !== body) { console.error(`view registry drift: regenerate with bun scripts/pilot/generate-view-registry.ts (${out})`); process.exit(1); }
	console.log(`view registry: ${entries.length} entries, up to date`);
} else {
	writeFileSync(out, body);
	console.log(`wrote ${out}: ${entries.length} entries`);
}
