import { expect, it } from 'vitest';
import { createCloudAssets } from '../../../src/lib/results/hosted/assets';
import { fastOriginals } from '../../../src/lib/viewer/hosted/fast-original';
import { grantedIdentity, ids, BUDGETS, deployment } from '../storage/fixture';
import { mintTicket, verifyTicket } from '../../../src/lib/viewer/hosted/ticket';
const row = {sha256:'a'.repeat(64),size:258_000_000,etag:'stored-tag',media_family:'pdf',media_type:'application/pdf',filename:'synthetic.pdf',object_key:'orig/'+ 'a'.repeat(64)};
it('view metadata 1 D1/0 R2; ticket range 0 D1/1 R2; unticketed GET 1 D1/1 R2; audit follows response', async () => {
 const dep = deployment('client-a',['case-a']);
 dep.db.exec('INSERT INTO rs_original (sha256,size,object_key,etag,media_family) VALUES (?,?,?,?,?)',row.sha256,row.size,row.object_key,row.etag,row.media_family);
 dep.db.exec('INSERT INTO rs_case_original (case_id,asset_id,sha256,filename,media_type,finalized_at) VALUES (?,?,?,?,?,?)','case-a','asset-a',row.sha256,row.filename,row.media_type,'2026-10-28T00:00:00Z');
 let d1=0,r2=0;
 const db = {prepare(sql:string) {d1++;return dep.db.prepare(sql);},batch:dep.db.batch.bind(dep.db)};
 const bucket = { ...dep.bucket, async get(_key:string, _options?:unknown) {r2++;return {key:row.object_key,version:'v1',checksums:{},arrayBuffer:async()=>{throw new Error('buffering forbidden');},size:row.size,etag:row.etag,body:new ReadableStream({start(c){c.enqueue(new Uint8Array([1,2]));c.close();}})};},head:dep.bucket.head.bind(dep.bucket),put:dep.bucket.put.bind(dep.bucket)};
 const {identity,grants}=grantedIdentity(ids.clientA,['case-a']);
 const pending: Promise<unknown>[] = [], order:string[]=[];
 const make = () => createCloudAssets({open:async()=>({db,bucket,clientId:ids.clientA,budgets:BUDGETS}),identity,record:async()=>{order.push('audit');},fastOriginals:true,ticketBucket:bucket,waitUntil:p=>{pending.push(p);}});
 const asset = {kind:'original' as const,caseId:ids.caseA,assetId:'asset-a'};
 const fast = fastOriginals(make())!;
 const metadata=await fast.locate(asset);
 expect({d1,r2}).toEqual({d1:1,r2:0});
 const t=await mintTicket(metadata,'key');
 const claims=await verifyTicket(t,'key','case-a','asset-a');
 if (!claims) throw new Error('ticket');
 grants.clear(); d1=0;r2=0;
 const response=await fastOriginals(make())!.get(asset,{method:'GET',range:'bytes=0-1',ifRange:null},claims);
 order.push('response');
 expect(response.status).toBe(206);
 expect((await response.arrayBuffer()).byteLength).toBe(2);
 expect({d1,r2}).toEqual({d1:0,r2:1});
 await Promise.all(pending); expect(order).toEqual(['response','audit']);
 grants.add('case-a');d1=0;r2=0;
 expect((await make().get({asset,request:{method:'GET',range:'bytes=0-1',ifRange:null}})).status).toBe(206);
 expect({d1,r2}).toEqual({d1:1,r2:1});
 await Promise.all(pending);
 d1=0;r2=0;
 await expect(fastOriginals(make())!.locate({...asset,caseId:ids.caseB})).rejects.toMatchObject({code:'forbidden'});
 expect(r2).toBe(0);
 await expect(fastOriginals(make())!.locate({...asset,assetId:'another-case-asset'})).rejects.toMatchObject({code:'not-found'});
 expect(r2).toBe(0);
});
