// `probe.ts --check` must refuse every mutation of a real PASS summary (GRS-109, after GRS-106's fix round). From this
// directory:
//
//   bun run --bun test:check
//
// It takes the committed evidence summary, points its SHA at HEAD so the control passes, then mutates every leaf and
// every container one at a time (delete, null, retype, empty string, flipped boolean, zeroed or negated number, an
// unknown key added to every object) and runs the real `--check` CLI on each file. Any mutation that prints CHECK PASS is
// a hole. The walk is over the summary itself, not over the checker's own field list, so a field the checker forgets
// cannot hide from it. Named cases run on top, so a regression names what it let through.
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const HERE = import.meta.dirname;
const EVIDENCE = path.join(HERE, '../../../docs/acceptance/hosting/evidence/storage-summary.json');
type Json = Record<string, unknown>;

const head = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: HERE, encoding: 'utf8' }).stdout.trim();
const base = JSON.parse(readFileSync(EVIDENCE, 'utf8')) as Json;
base.sourceSha = head;

const dir = mkdtempSync(path.join(tmpdir(), 'storage-check-'));
let n = 0;
function check(summary: unknown): Promise<{ pass: boolean; out: string }> {
	const file = path.join(dir, `m${n++}.json`);
	writeFileSync(file, JSON.stringify(summary));
	return new Promise((resolve) => {
		const child = spawn(process.execPath, ['probe.ts', '--check', file], { cwd: HERE, env: { PATH: process.env.PATH ?? '' }, stdio: ['ignore', 'pipe', 'pipe'] });
		let out = '';
		child.stdout.on('data', (b: Buffer) => (out += b));
		child.stderr.on('data', (b: Buffer) => (out += b));
		child.on('close', (code) => resolve({ pass: code === 0 && out.includes('CHECK PASS'), out: out.trim() }));
	});
}

type Edit = (summary: Json) => void;
const at = (summary: Json, p: (string | number)[]) => p.slice(0, -1).reduce<any>((o, k) => o[k], summary);
const mutations: [string, Edit][] = [];

function walk(value: unknown, p: (string | number)[]) {
	const label = p.join('.') || '<root>';
	if (p.length) {
		const key = p.at(-1)!;
		mutations.push([`${label} deleted`, (s) => (Array.isArray(at(s, p)) ? at(s, p).splice(key as number, 1) : delete at(s, p)[key])]);
		if (value !== null) mutations.push([`${label} null`, (s) => (at(s, p)[key] = null)]);
		mutations.push([`${label} retyped`, (s) => (at(s, p)[key] = typeof value === 'string' ? 1 : typeof value === 'object' && value !== null ? 'x' : String(value))]);
		if (typeof value === 'string') mutations.push([`${label} emptied`, (s) => (at(s, p)[key] = '')]);
		if (typeof value === 'boolean') mutations.push([`${label} flipped`, (s) => (at(s, p)[key] = !value)]);
		if (typeof value === 'number' && value !== 0) mutations.push([`${label} zeroed`, (s) => (at(s, p)[key] = 0)]);
		if (typeof value === 'number') mutations.push([`${label} negated`, (s) => (at(s, p)[key] = -1 - value)]);
	}
	if (Array.isArray(value)) value.forEach((v, i) => walk(v, [...p, i]));
	else if (typeof value === 'object' && value !== null) {
		mutations.push([`${label} + unknown key`, (s) => ((p.reduce<any>((o, k) => o[k], s) as Json).__unknown = 1)]);
		for (const [k, v] of Object.entries(value)) walk(v, [...p, k]);
	}
}
walk(base, []);

const legs = (s: Json) => s.legs as Record<string, { measured: Json; failure?: string; asserted: string[] }>;
const named: [string, Edit][] = [
	['scale smoke', (s) => (s.scale = 'smoke')],
	['a cloud leg dropped from hold', (s) => (s.hold as string[]).splice(0, 1)],
	['hold entry changed to done', (s) => ((s.hold as string[])[4] = 'P6 Time Travel restore: PASS')],
	['an upload failure', (s) => (legs(s).upload!.measured.failures = 1)],
	['a duplicate seq', (s) => (legs(s)['user-work']!.measured.duplicateSeqs = 1)],
	['the control found no duplicate', (s) => (legs(s)['user-work']!.measured.naiveDuplicateSeqs = 0)],
	['two replaces written', (s) => (legs(s)['user-work']!.measured.staleReplaces = 18)],
	['a corruption case served', (s) => (legs(s).corruption!.measured.casesRefused = 7)],
	['fewer crossed refusals', (s) => (legs(s)['crossed-bindings']!.measured.refusedRequests = 8)],
	['the document page reads R2', (s) => (legs(s).layout!.measured.documentPageR2Ops = 1)],
	['generated bytes differ from the target', (s) => void ((((s.corpus as Json).generated as Json).originals as Json).bytes = 3_211_390_881)],
	['failure string on a PASS leg', (s) => (legs(s).restore!.failure = 'assertion failed: x')],
	['an assertion dropped', (s) => legs(s).corruption!.asserted.pop()],
	['CLOUDFLARE_API_TOKEN added to isolation.env', (s) => (s.isolation as { env: string[] }).env.push('CLOUDFLARE_API_TOKEN')],
	['hosts.wrangler = "Bun 1.4.2"', (s) => ((s.hosts as Json).wrangler = 'Bun 1.4.2')],
	['checker.accepted set', (s) => ((s.checker as Json).accepted = 'schema deleted')],
	['absolute runDir', (s) => (s.runDir = '/home/someone/run')],
];

const control = await check(base);
const results: string[] = [];
if (!control.pass) results.push(`control: the unmutated PASS summary is refused:\n${control.out}`);
const all = [...mutations, ...named];
const queue = [...all];
let accepted = 0;
let ran = 0;
await Promise.all(
	Array.from({ length: 8 }, async () => {
		for (let m = queue.shift(); m; m = queue.shift()) {
			const copy = structuredClone(base);
			m[1](copy);
			if (JSON.stringify(copy) === JSON.stringify(base)) continue; // not a mutation
			ran++;
			if ((await check(copy)).pass) (accepted++, results.push(`ACCEPTED: ${m[0]}`));
		}
	}),
);
rmSync(dir, { recursive: true, force: true });
console.log(results.sort().join('\n'));
console.log(accepted || !control.pass ? `MUTATION CHECK FAIL: ${accepted} of ${ran} mutations accepted` : `MUTATION CHECK PASS: ${ran} mutations refused`);
process.exit(accepted || !control.pass ? 1 : 0);
